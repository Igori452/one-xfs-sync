#pragma once

#include <cstdint>

#include <vector>
#include <map>
#include <span>

#include "one-xfs-sync/epoll_manager/epoll_manager.h"

/**
 * @brief Инфраструктурный адаптер для буферизованной неблокирующей отправки данных.
 *
 * Инкапсулирует логику обработки частичной записи (partial writes) в TCP-сокеты,
 * сохраняя недоотправленные хвосты в динамической памяти C++ и автоматически
 * взаимодействуя с механизмом EPOLLOUT через net_loop_t.
 * Не владеет ни экземпляром net_loop_t, ни файловыми дескрипторами сокетов.
 */
class net_dispatcher 
{
    private:
        /**
         * @brief Буфер исходящих данных для отдельного соединения.
         */
        struct out_queue 
        {
            std::vector<uint8_t> buffer;        ///< Накопитель неотправленных байтов (сохраняет capacity при очистке).
            std::size_t offset {0};             ///< Смещение начала неотправленного остатка (позволяет избежать смещения в vector).
        };

        std::map<int, out_queue> out_queue_;    ///< Очереди отправки, индексированные по дескриптору сокета (fd).
        net_loop_t* net_loop_ {nullptr};        ///< Невладеющий указатель на низкоуровневый событийный цикл.

    public:
        net_dispatcher() = delete;

        /**
         * @brief Конструирует диспетчер с привязкой к существующему событийному циклу.
         * @param net_loop Указатель на инициализированный экземпляр net_loop_t.
         */
        explicit net_dispatcher(net_loop_t* net_loop) noexcept;

        net_dispatcher(const net_dispatcher&) = delete;
        net_dispatcher& operator=(const net_dispatcher&) = delete;

        /**
         * @brief Инициирует неблокирующую отправку данных в указанный сокет.
         *
         * Если исходящая очередь для fd пуста, выполняет прямую попытку отправки.
         * Если ядро приняло только часть данных (или очередь уже не пуста),
         * помещает остаток в буфер для последующей доотправки по событию NET_EVENT_WRITE.
         *
         * @param fd   Дескриптор клиентского сокета.
         * @param data Представление буфера данных для отправки.
         * @return true, если данные отправлены или успешно поставлены в очередь;
         *         false при фатальной ошибке сокета или невалидных параметрах.
         */
        bool send(int fd, std::span<const uint8_t> data);

        /**
         * @brief Обрабатывает событие готовности сокета к записи (NET_EVENT_WRITE).
         *
         * Доотправляет накопленный в out_queue_ остаток данных начиная с текущего offset.
         * При опустошении буфера сбрасывает offset и очищает вектор без освобождения памяти.
         *
         * @param fd Дескриптор сокета, готового к записи.
         * @return true при успешной доотправке (полной или частичной);
         *         false при обрыве соединения или ошибке системного вызова.
         */
        bool on_writable(int fd);

        /**
         * @brief Прерывает процесс текущей отправки, удаляет исходящую очередь указанного сокета и освобождает память.
         *
         * Должен вызываться при закрытии соединения или получении события NET_EVENT_ERROR.
         *
         * @param fd Дескриптор закрываемого сокета.
         */
        void clear_queue(int fd);

        /**
         * @brief Проверяет наличие неотправленных данных в очереди сокета.
         * @param fd Дескриптор сокета.
         * @return true, если в буфере остаются данные для отправки; иначе false.
         */
        bool has_pending(int fd) const noexcept;
};